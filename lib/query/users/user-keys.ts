export const userKeys = {
  // ============================================================
  // ALL USER QUERIES
  // ============================================================

  all: ["users"] as const,

  // ============================================================
  // CURRENT USER
  // ============================================================

  current: () =>
    [...userKeys.all, "current"] as const,

  // ============================================================
  // ADMIN USER QUERIES
  // ============================================================

  admin: () =>
    [...userKeys.all, "admin"] as const,

  // ============================================================
  // ADMIN USER LIST
  // ============================================================

  adminList: (
    params: object,
  ) =>
    [
      ...userKeys.admin(),
      "list",
      params,
    ] as const,

  // ============================================================
  // ADMIN USER DETAILS
  // ============================================================

  adminDetail: (
    id: string,
  ) =>
    [
      ...userKeys.admin(),
      "detail",
      id,
    ] as const,

  // ============================================================
  // ADMIN USER ORDERS
  // ============================================================

  adminOrders: (
    id: string,
    params: object = {},
  ) =>
    [
      ...userKeys.admin(),
      "orders",
      id,
      params,
    ] as const,
};